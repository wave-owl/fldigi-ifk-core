#!/usr/bin/env python3
"""Generate src/ifk_tables.c from fldigi 4.2.13's varicode sources (stdlib only).

    python3 tools/gen_tables.py /path/to/fldigi > src/ifk_tables.c

Copies THOR's secondary varicode (src/thor/thorvaricode.cxx) and the DominoEX nibble
varicode (src/dominoex/dominovar.cxx) verbatim into C arrays, each with the fldigi lines
it comes from, so the tables cannot drift from fldigi by a typing error.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import re
import sys
from pathlib import Path


def lines_of(root, rel):
    return (Path(root) / rel).read_text(encoding="latin-1").split("\n")


def block(lines, start_pat):
    for i, l in enumerate(lines):
        if re.search(start_pat, l):
            j = i + 1
            while not lines[j].startswith("};"):
                j += 1
            return i, j
    raise SystemExit("not found: " + start_pat)


def main():
    root = sys.argv[1]
    thor = lines_of(root, "src/thor/thorvaricode.cxx")
    dom = lines_of(root, "src/dominoex/dominovar.cxx")
    a, b = block(thor, r"static const char \*thor_varicode\[\]")
    codes = [m.group(1) for l in thor[a + 1:b] for m in [re.search(r'"([01]+)"', l)] if m]
    c, d = block(thor, r"static const unsigned int thor_varidecode\[\]")
    dec = [int(x, 16) for l in thor[c + 1:d] for x in re.findall(r"0x[0-9A-Fa-f]+", l)]
    assert len(codes) == 91 and len(dec) == 91
    assert all(int(x, 2) == y for x, y in zip(codes, dec))
    e, f = block(dom, r"static unsigned char varicode\[\]\[3\]")
    trip = [tuple(int(v) for v in t) for l in dom[e + 1:f]
            for t in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+)\}", l)]
    assert len(trip) == 512, len(trip)
    g, h = block(dom, r"static signed int varidecode\[\]")
    vd = [int(x) for l in dom[g + 1:h] for x in re.findall(r"-?\d+", l)]
    assert len(vd) == 4096, len(vd)
    out = []
    out.append("/* Generated by tools/gen_tables.py from fldigi 4.2.13 (tag v4.2.13, commit")
    out.append(" * e7c3ab3709ad62a7d91829364eb48a05fa325c0d). Do not edit.")
    out.append(" * SPDX-License-Identifier: GPL-3.0-or-later */")
    out.append('#include "ifk_internal.h"')
    out.append("")
    out.append("/* thor_varicode[], thor/thorvaricode.cxx:%d-%d: secondary set ' ' .. 'z' */"
               % (a + 1, b + 1))
    out.append("const char *const fifk_thor_varicode[91] = {")
    for k in range(0, 91, 4):
        out.append("    " + ", ".join('"%s"' % x for x in codes[k:k + 4]) + ",")
    out.append("};")
    out.append("")
    out.append("/* thor_varidecode[], thor/thorvaricode.cxx:%d-%d */" % (c + 1, d + 1))
    out.append("const unsigned int fifk_thor_varidecode[91] = {")
    for k in range(0, 91, 8):
        out.append("    " + ", ".join("0x%03X" % x for x in dec[k:k + 8]) + ",")
    out.append("};")
    out.append("")
    out.append("/* varicode[][3], dominoex/dominovar.cxx:%d-%d: primary 0..255, secondary"
               % (e + 1, f + 1))
    out.append(" * 256..511 */")
    out.append("const unsigned char fifk_dominoex_varicode[512][3] = {")
    for k in range(0, 512, 8):
        out.append("    " + ", ".join("{%d, %d, %d}" % t for t in trip[k:k + 8]) + ",")
    out.append("};")
    out.append("")
    out.append("/* varidecode[], dominoex/dominovar.cxx:%d-%d */" % (g + 1, h + 1))
    out.append("const short fifk_dominoex_varidecode[4096] = {")
    for k in range(0, 4096, 16):
        out.append("    " + ", ".join("%d" % v for v in vd[k:k + 16]) + ",")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
